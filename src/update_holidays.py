"""Pull Malaysian public holidays for Perak (where UTP is) into the dashboard.

Source: the open-source `holidays` library (https://github.com/vacanza/holidays), which
tracks the official federal and Perak state holiday gazette, including replacement days
and the Sultan of Perak's birthday. A GitHub Action (.github/workflows/update-holidays.yml)
runs this script every week with the newest library version, so newly gazetted or moved
holidays reach the dashboard without anyone typing them in.

The dashboard merges this list with the public holidays printed in the UTP academic
calendar (docs/data/academic_calendar.js). A date that is a holiday in either list is
treated as "Holiday / break".

Usage:  python src/update_holidays.py
"""
import datetime as dt
import json
from importlib.metadata import version

import holidays

from config import ROOT

OUT = ROOT / "docs" / "data" / "public_holidays.js"
SUBDIV = "PRK"  # Perak


def main() -> list[dict]:
    this_year = dt.date.today().year
    years = list(range(this_year - 1, this_year + 3))
    national = holidays.Malaysia(years=years, language="en_US")
    perak = holidays.Malaysia(subdiv=SUBDIV, years=years, language="en_US")

    rows = []
    for day, names in sorted(perak.items()):
        rows.append({
            "date": day.isoformat(),
            "name": names.replace("; ", " / "),
            "scope": "national" if day in national else "Perak",
        })

    j = lambda v: json.dumps(v, ensure_ascii=False)
    source = f"Malaysia public holidays for Perak · python-holidays {version('holidays')}"
    updated = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = ",\n".join(f"    {j(r)}" for r in rows)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "/* Generated by src/update_holidays.py - do not edit by hand.\n"
        " * Refreshed every week by .github/workflows/update-holidays.yml. */\n"
        "window.PUBLIC_HOLIDAYS = {\n"
        f'  "source": {j(source)},\n'
        f'  "updated": {j(updated)},\n'
        f'  "years": {j([years[0], years[-1]])},\n'
        f'  "holidays": [\n{lines}\n  ]\n'
        "};\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(rows)} Perak public holidays ({years[0]}-{years[-1]}) to {OUT.relative_to(ROOT)}")
    return rows


if __name__ == "__main__":
    main()
